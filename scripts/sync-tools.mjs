// Regenerates src/tools.json from a running Bytebase instance.
//
// Bytebase's built-in MCP server answers tools/list only to a signed-in
// session, so this connects the same way the package does (OAuth in the
// browser, token cached under BYTEBASE_MCP_HOME) and dumps what the instance
// serves. Run it against each release before publishing:
//
//   npm run build
//   BYTEBASE_URL=https://your-bytebase npm run sync-tools
//
// The dump strips the two per-session parts of the initialize instructions:
// the opening line that names the signed-in account, and the closing paragraph
// Bytebase adds for clients that declared no elicitation form.
import fs from "node:fs";
import path from "node:path";
import { loadConfig } from "../dist/config.js";
import { Upstream } from "../dist/upstream.js";

const root = path.join(import.meta.dirname, "..");
const out = path.join(root, "src", "tools.json");

const config = loadConfig(process.env, process.argv[2]);
if (!config.url) {
  console.error("usage: BYTEBASE_URL=<url> node scripts/sync-tools.mjs   (or pass the URL as the first argument)");
  process.exit(2);
}

const upstream = new Upstream(
  { ...config, url: config.url },
  {
    // Declare a form so Bytebase serves the instructions written for clients that can confirm.
    clientCapabilities: () => ({ elicitation: { form: {} } }),
    onElicit: async () => ({ action: "cancel" }),
  },
);

const client = await upstream.get();
const serverInfo = client.getServerVersion();
const rawInstructions = client.getInstructions() ?? "";
const { tools } = await upstream.listTools();
upstream.reset();

let instructions = rawInstructions;
const paragraphs = instructions.split("\n\n");
if (paragraphs[0]?.startsWith("In workspaces/") || /this session acts as the Bytebase account/.test(paragraphs[0] ?? "")) {
  paragraphs.shift();
}
if (/cannot show Bytebase's confirmation form/.test(paragraphs.at(-1) ?? "")) {
  paragraphs.pop();
}
instructions = paragraphs.join("\n\n");

const previous = fs.existsSync(out) ? JSON.parse(fs.readFileSync(out, "utf8")) : undefined;
const result = {
  $comment: "Generated by scripts/sync-tools.mjs from a Bytebase instance's built-in MCP server. Do not edit by hand; rerun `npm run sync-tools`.",
  bytebaseVersion: serverInfo?.version ?? "unknown",
  generatedAt: new Date().toISOString(),
  instructions,
  tools,
};
fs.writeFileSync(out, JSON.stringify(result, null, 2) + "\n");

const before = new Set((previous?.tools ?? []).map((t) => t.name));
const after = new Set(tools.map((t) => t.name));
const added = [...after].filter((n) => !before.has(n));
const removed = [...before].filter((n) => !after.has(n));
console.log(`wrote ${path.relative(root, out)}: ${tools.length} tools from Bytebase ${result.bytebaseVersion}`);
if (added.length) console.log(`  added:   ${added.join(", ")}`);
if (removed.length) console.log(`  removed: ${removed.join(", ")}`);
if (previous && !added.length && !removed.length) {
  const changed = tools.filter((t) => JSON.stringify(t) !== JSON.stringify(previous.tools.find((p) => p.name === t.name))).map((t) => t.name);
  console.log(changed.length ? `  changed: ${changed.join(", ")}` : "  no tool changed");
}

await import("./render-readme.mjs");
